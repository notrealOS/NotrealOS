#!/usr/bin/env python3
"""Write ~/.config/gtk-3.0/gtk.css for the active theme: @define-color nr_* from its palette,
then themes/gtk3-common.css (layout) and themes/<name>.gtk3.css. Prints 'changed' if it changed."""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import notareal_theme as t

name = t.active()
T = t.THEMES
out = os.path.expanduser("~/.config/gtk-3.0/gtk.css")
parts = [f"/* GENERATED by ~/theme/nrtheme for theme '{name}' - edit ~/theme/themes/{name}.gtk3.css instead */\n"]
parts += [f"@define-color nr_{k.replace('-', '_')} {v};" for k, v in sorted(t.palette().items())]
for f in ("gtk3-common.css", f"{name}.gtk3.css"):
    p = os.path.join(T, f)
    if os.path.exists(p):
        parts.append(open(p).read())
css = "\n".join(parts) + "\n"
old = open(out).read() if os.path.exists(out) else ""
if css != old:
    open(out + ".tmp", "w").write(css)
    os.replace(out + ".tmp", out)
    print("changed")
